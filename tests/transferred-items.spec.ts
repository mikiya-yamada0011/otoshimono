import {test,expect} from '@playwright/test';
for(const width of [390,640,1200]) test(`移管済みの検索・詳細・申込案内を確認する（${width}px）`,async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.goto('/?role=student');
 await page.evaluate(()=>{
  const key='lost-found-no-qr-test-harness-v1',db=JSON.parse(localStorage.getItem(key)!);
  const item=db.public.find((row:any)=>row.value.sourceId==='1');
  item.value={...item.value,status:'移管済み',transferredAt:'2026/10/27',transferDestination:'灘警察署'};
  db.public.push({...item,id:'90',value:{...item.value,sourceId:'90',status:'返却済み',title:'公開しない返却品'}});
  db.public.push({...item,id:'91',value:{...item.value,sourceId:'91',valuable:true,title:'公開しない連絡先あり品'}});
  db.requests=[{id:'80',author:'student-1',etag:'1',value:{criteria:{parent:'P05',category:'P05_UMBRELLA_LONG',colors:[],campuses:[],building:'',dateFrom:'',dateTo:'',query:''},feature:'木の持ち手',status:'ACTIVE',createdAt:'2026-10-26T00:00:00Z'}}];
  db.claims=[{id:'80',author:'student-1',etag:'1',value:{itemId:'1',requestId:'80',email:'s260001@stu.kobe-u.ac.jp',feature:'木の持ち手',title:'長傘',window:'農学部事務室',status:'PENDING',createdAt:'2026-10-26T00:00:00Z',returnedAt:''}}];
  db.notices=[{id:'80',author:'staff-1',etag:'1',value:{owner:'student-1',email:'s260001@stu.kobe-u.ac.jp',itemId:'1',requestId:'80',kind:'MATCH',title:'長傘',window:'農学部事務室',message:'候補',createdAt:'2026-10-26T00:00:00Z'}}];
  db.notices.push({...db.notices[0],id:'81',value:{...db.notices[0].value,itemId:'2'}});
  localStorage.setItem(key,JSON.stringify(db));
 });
 await page.reload();
 const stored=page.getByRole('button',{name:'学内保管中',exact:true});
 await expect(stored).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('.lf-item-card').filter({hasText:'長傘'})).toHaveCount(0);
 await page.getByRole('button',{name:'警察へ移管済み',exact:true}).click();
 await expect(page.locator('.lf-item-card')).toHaveCount(1);
 await expect(page.locator('.lf-item-card')).toContainText('灘警察署');
 await page.locator('.lf-item-card').click();
 const dialog=page.getByRole('dialog');
 await expect(dialog).toContainText('2026/10/27');
 await expect(dialog).toContainText('灘警察署');
 await expect(dialog.getByRole('button',{name:'自分のものだと思う'})).toHaveCount(0);
 await page.keyboard.press('Escape');
 const nav=page.getByRole('navigation',{name:'学生メニュー'});
 await nav.getByRole('button',{name:'紛失した物',exact:true}).click();
 await expect(page.locator('.lf-record-card')).toHaveCount(1);
 await expect(page.locator('.lf-record-card .lf-badge')).toHaveText('警察へ移管済み');
 await expect(page.locator('.lf-record-card')).toContainText('灘警察署');
 await expect(page.locator('.lf-record-card').getByText('候補を見る（1件）',{exact:true})).toBeVisible();
 await expect(page.locator('.lf-record-card')).not.toContainText('窓口で学校メールを伝え');
 await page.getByRole('button',{name:'終了分',exact:true}).click();
 await expect(page.locator('.lf-record-card')).toHaveCount(0);
 await nav.getByRole('button',{name:'お知らせ',exact:true}).click();
 await expect(page.getByRole('main')).toContainText('この候補は警察へ移管しました。');
 await expect(page.getByRole('main')).toContainText('灘警察署');
 await expect(page.getByRole('main').locator('article').filter({hasText:'この候補は警察へ移管しました。'}).getByRole('button',{name:'候補を確認',exact:true})).toHaveCount(0);
 expect(await page.locator('body').evaluate(el=>el.scrollWidth)).toBeLessThanOrEqual(width);
 await page.screenshot({path:`temp/screenshots/transferred-notice-${width}.png`});
 await nav.getByRole('button',{name:'探す',exact:true}).click();
 await page.getByRole('button',{name:'警察へ移管済み',exact:true}).click();
 await expect(page.getByRole('button',{name:'警察へ移管済み',exact:true})).toHaveCSS('border-bottom-color','rgb(33, 102, 83)');
 await expect(page.getByRole('button',{name:'学内保管中',exact:true})).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
 await expect(page.getByRole('button',{name:'警察へ移管済み',exact:true})).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
 await expect(page.getByRole('button',{name:'学内保管中',exact:true})).toHaveCSS('text-decoration-line','none');
 await expect(page.getByRole('button',{name:'警察へ移管済み',exact:true})).toHaveCSS('font-weight','600');
 await page.screenshot({path:`temp/screenshots/transferred-search-${width}.png`});
});
